#include "libft.h"
#include <limits.h>
#include <unistd.h>

void	ft_putnbr_fd(int nbr, int fd)
{
	if (nbr == INT_MIN)
	{
		write(fd, "-2147483648", 11);
		return ;
	}
	if (nbr < 0)
	{
		write(fd, "-", 1);
		nbr = -nbr;
	}
	if (nbr >= 10)
		ft_putnbr_fd(nbr / 10, fd);
	ft_putchar_fd((nbr % 10) + '0', fd);
}
